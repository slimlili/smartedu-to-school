# ---------- 智能匹配 ----------
# 同一任务号出现多条时（平台把阅读/例题分成同名任务），用关键词从题干正文区分。
# 键后缀(·X) → 应在任务正文出现的特征词
_CUE_KEYS = {
    "阅读": ["阅读课本"],
    "例题1": ["例题1", "例题 1"],
    "例题": ["例题"],
    "多级": ["多级加速器"],
    "做功": ["做功", "WAB", "电势差与电场力"],
    "定义": ["定义式", "定义", "UAB＝", "UAB="],
    "实验": ["观察实验", "实验视频", "实验操作", "模拟实验", "推测"],
}


def pick_task_answer(lesson_key, task_title, body):
    """lesson_key: 课时名；task_title: 如 学习任务一；body: 该任务正文。
    返回解析文本(HTML/plain) 或 None。"""
    import re as _re
    # 归一化任务标题里的 数字
    m = _re.match(r'[【】\s]*学习任务([一二三四五六七八九十\d]+)[【】\s]*', task_title or "")
    base = f"学习任务{m.group(1)}" if m else (task_title or "").strip()
    cands = []
    for (ls, tt), val in TASK_ANSWERS.items():
        if ls != lesson_key:
            continue
        if tt == base or tt.startswith(base + "·"):
            cands.append((tt, val))
    if not cands:
        return None
    if len(cands) == 1:
        return cands[0][1]
    # 多条：按 cue 关键词匹配正文
    for tt, val in cands:
        suffix = tt.split("·", 1)[1] if "·" in tt else ""
        for kw in _CUE_KEYS.get(suffix, []):
            if kw in (body or ""):
                return val
    # 兜底取含“例题”的，否则第一条
    for tt, val in cands:
        if "例题" in tt:
            return val
    return cands[0][1]


